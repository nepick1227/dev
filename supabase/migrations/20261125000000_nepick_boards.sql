-- 게시판 목록
CREATE FUNCTION public.nepick_list_boards()
RETURNS TABLE (
  board_id bigint,
  slug text,
  food_name text,
  store_count integer,
  pick_count integer,
  top_store_name text,
  top_nepick_index integer
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = ''
AS $$
  SELECT
    board.id,
    board.slug,
    board.food_name,
    COALESCE(summary.store_count, 0),
    COALESCE(summary.pick_count, 0),
    top_store.name,
    top_store.nepick_index
  FROM public.nepick_boards AS board
  LEFT JOIN LATERAL (
    SELECT
      COUNT(*)::integer AS store_count,
      SUM(visible.nepick_index)::integer AS pick_count
    FROM public.nepick_visible_board_stores AS visible
    WHERE visible.board_id = board.id
  ) AS summary ON true
  LEFT JOIN LATERAL (
    SELECT store.name, visible.nepick_index
    FROM public.nepick_visible_board_stores AS visible
    JOIN public.stores AS store ON store.id = visible.store_id
    WHERE visible.board_id = board.id AND visible.nepick_index > 0
    ORDER BY visible.nepick_index DESC, visible.vote_score DESC, visible.created_at, visible.id
    LIMIT 1
  ) AS top_store ON true
  WHERE board.is_active
  ORDER BY board.sort_order, board.id;
$$;

-- 게시판 안 가게 순위. 비로그인은 p_viewer_id에 NULL을 넘긴다.
CREATE FUNCTION public.nepick_list_board_stores(p_board_id bigint, p_viewer_id uuid DEFAULT NULL)
RETURNS TABLE (
  board_store_id bigint,
  store_id bigint,
  name text,
  category text,
  subcategory text,
  address text,
  road_address text,
  nepick_index integer,
  up_count integer,
  post_count integer,
  is_my_pick boolean,
  my_vote smallint
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = ''
AS $$
  SELECT
    visible.id,
    store.id,
    store.name,
    store.category,
    store.subcategory,
    store.address,
    store.road_address,
    visible.nepick_index,
    visible.up_count,
    visible.post_count,
    EXISTS (
      SELECT 1
      FROM public.nepick_picks AS my_pick
      WHERE my_pick.board_store_id = visible.id AND my_pick.user_id = p_viewer_id
    ),
    COALESCE(my_vote.value, 0::smallint)
  FROM public.nepick_visible_board_stores AS visible
  JOIN public.stores AS store ON store.id = visible.store_id
  LEFT JOIN public.nepick_votes AS my_vote
    ON my_vote.board_store_id = visible.id AND my_vote.user_id = p_viewer_id
  WHERE visible.board_id = p_board_id
  ORDER BY visible.nepick_index DESC, visible.vote_score DESC, visible.created_at, visible.id;
$$;

-- 가게 카드의 글. p_board_store_id가 있으면 그 가게만, p_per_store가 있으면 가게마다 앞에서 N개만.
-- 탈퇴한 사람의 닉네임은 다른 사람이 다시 쓸 수 있으므로 NULL로 내려 준다.
CREATE FUNCTION public.nepick_list_posts(
  p_board_id bigint,
  p_viewer_id uuid DEFAULT NULL,
  p_board_store_id bigint DEFAULT NULL,
  p_per_store integer DEFAULT NULL
)
RETURNS TABLE (
  post_id bigint,
  board_store_id bigint,
  nickname text,
  body text,
  is_picker boolean,
  is_mine boolean,
  created_at timestamptz
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = ''
AS $$
  WITH numbered AS (
    SELECT
      post.id,
      post.board_store_id,
      post.user_id,
      post.body,
      post.created_at,
      ROW_NUMBER() OVER (
        PARTITION BY post.board_store_id
        ORDER BY post.created_at, post.id
      ) AS position
    FROM public.nepick_posts AS post
    JOIN public.nepick_visible_board_stores AS visible ON visible.id = post.board_store_id
    WHERE visible.board_id = p_board_id
      AND (p_board_store_id IS NULL OR visible.id = p_board_store_id)
      AND NOT post.is_hidden
      AND post.deleted_at IS NULL
  )
  SELECT
    numbered.id,
    numbered.board_store_id,
    CASE WHEN profile.deleted_at IS NULL THEN profile.nickname END,
    numbered.body,
    EXISTS (
      SELECT 1
      FROM public.nepick_active_picks AS pick
      WHERE pick.board_store_id = numbered.board_store_id
        AND pick.user_id = numbered.user_id
    ),
    numbered.user_id IS NOT DISTINCT FROM p_viewer_id,
    numbered.created_at
  FROM numbered
  JOIN public.profiles AS profile ON profile.id = numbered.user_id
  WHERE p_per_store IS NULL OR numbered.position <= p_per_store
  ORDER BY numbered.board_store_id, numbered.created_at, numbered.id;
$$;

-- 홈 가게 카드 뱃지: 네픽지수가 1 이상인 게시판만
CREATE FUNCTION public.nepick_list_store_badges(p_store_id bigint)
RETURNS TABLE (slug text, food_name text, nepick_index integer)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = ''
AS $$
  SELECT board.slug, board.food_name, visible.nepick_index
  FROM public.nepick_visible_board_stores AS visible
  JOIN public.nepick_boards AS board ON board.id = visible.board_id
  WHERE visible.store_id = p_store_id AND visible.nepick_index > 0
  ORDER BY visible.nepick_index DESC, board.sort_order, board.id;
$$;

-- ------------------------------------------------------------
-- 5. 쓰기 함수
--    실패는 nepick_로 시작하는 오류 이름으로 알린다. 서버 라우트가 안내 문구로 바꾼다.
-- ------------------------------------------------------------

-- 쓰기 공통: 같은 사용자의 쓰기를 한 줄로 세우고(연타·동시 요청), 활동 가능한 계정인지 확인한다.
CREATE FUNCTION public.nepick_begin_write(p_user_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
  IF p_user_id IS NULL THEN
    RAISE EXCEPTION 'nepick_authentication_required';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended('nepick:' || p_user_id::text, 0));

  IF NOT EXISTS (
    SELECT 1
    FROM public.profiles AS profile
    WHERE profile.id = p_user_id
      AND profile.deleted_at IS NULL
      AND btrim(COALESCE(profile.nickname, '')) <> ''
  ) THEN
    RAISE EXCEPTION 'nepick_profile_inactive';
  END IF;
END;
$$;

-- 글 저장 공통: 1분에 5개, 24시간에 50개까지. 삭제한 글도 센다.
CREATE FUNCTION public.nepick_insert_post(p_user_id uuid, p_board_store_id bigint, p_body text)
RETURNS bigint
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_body text := btrim(COALESCE(p_body, ''), E' \t\r\n');
  v_post_id bigint;
BEGIN
  IF char_length(v_body) NOT BETWEEN 1 AND 200 THEN
    RAISE EXCEPTION 'nepick_invalid_text';
  END IF;

  IF (
    SELECT COUNT(*) FILTER (WHERE post.created_at > now() - interval '1 minute') >= 5
      OR COUNT(*) >= 50
    FROM public.nepick_posts AS post
    WHERE post.user_id = p_user_id AND post.created_at > now() - interval '24 hours'
  ) THEN
    RAISE EXCEPTION 'nepick_rate_limited';
  END IF;

  INSERT INTO public.nepick_posts (board_store_id, user_id, body)
  VALUES (p_board_store_id, p_user_id, v_body)
  RETURNING id INTO v_post_id;

  RETURN v_post_id;
END;
$$;

-- 추천하기: 가게 등록, 글, 추천, 자동 기록이 한 번에 성공하거나 모두 취소된다.
-- 이미 다른 가게를 추천한 게시판이면 p_allow_switch가 true일 때만 바꾼다(화면에서 확인을 받은 뒤).
CREATE FUNCTION public.nepick_pick_store(
  p_user_id uuid,
  p_board_id bigint,
  p_store_id bigint,
  p_reason text,
  p_allow_switch boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_board_store_id bigint;
  v_is_hidden boolean;
  v_previous_id bigint;
  v_post_id bigint;
  v_record_created boolean := false;
BEGIN
  PERFORM public.nepick_begin_write(p_user_id);

  IF NOT EXISTS (
    SELECT 1 FROM public.nepick_boards AS board WHERE board.id = p_board_id AND board.is_active
  ) THEN
    RAISE EXCEPTION 'nepick_board_not_found';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.stores AS store WHERE store.id = p_store_id) THEN
    RAISE EXCEPTION 'nepick_store_not_found';
  END IF;

  INSERT INTO public.nepick_board_stores (board_id, store_id, created_by)
  VALUES (p_board_id, p_store_id, p_user_id)
  ON CONFLICT (board_id, store_id) DO NOTHING;

  SELECT board_store.id, board_store.is_hidden
  INTO v_board_store_id, v_is_hidden
  FROM public.nepick_board_stores AS board_store
  WHERE board_store.board_id = p_board_id AND board_store.store_id = p_store_id;

  IF v_is_hidden THEN
    RAISE EXCEPTION 'nepick_store_hidden';
  END IF;

  SELECT pick.board_store_id
  INTO v_previous_id
  FROM public.nepick_picks AS pick
  WHERE pick.board_id = p_board_id AND pick.user_id = p_user_id;

  IF v_previous_id = v_board_store_id THEN
    RAISE EXCEPTION 'nepick_already_picked';
  END IF;

  IF v_previous_id IS NOT NULL AND NOT COALESCE(p_allow_switch, false) THEN
    RAISE EXCEPTION 'nepick_switch_required';
  END IF;

  v_post_id := public.nepick_insert_post(p_user_id, v_board_store_id, p_reason);

  DELETE FROM public.nepick_picks AS pick
  WHERE pick.board_id = p_board_id AND pick.user_id = p_user_id;

  INSERT INTO public.nepick_picks (board_id, board_store_id, user_id, reason_post_id)
  VALUES (p_board_id, v_board_store_id, p_user_id, v_post_id);

  -- 내 한 곳으로 고른 가게에는 추천/비추천을 누를 수 없으므로 눌러 둔 것을 지운다
  DELETE FROM public.nepick_votes AS vote
  WHERE vote.board_store_id = v_board_store_id AND vote.user_id = p_user_id;

  -- 이 가게에 내 기록이 없을 때만 자동으로 남긴다
  IF NOT EXISTS (
    SELECT 1
    FROM public.records AS record
    WHERE record.user_id = p_user_id AND record.store_id = p_store_id
  ) THEN
    INSERT INTO public.records (user_id, store_id, recommendation, comment, visited_at)
    SELECT p_user_id, p_store_id, 'recommend', post.body, now()
    FROM public.nepick_posts AS post
    WHERE post.id = v_post_id;
    v_record_created := true;
  END IF;

  RETURN jsonb_build_object(
    'board_store_id', v_board_store_id,
    'post_id', v_post_id,
    'previous_board_store_id', v_previous_id,
    'record_created', v_record_created
  );
END;
$$;

-- 추천 철회: 글과 기록은 남고 딱지와 지수만 빠진다. 추천이 없었으면 false.
CREATE FUNCTION public.nepick_unpick(p_user_id uuid, p_board_id bigint)
RETURNS boolean
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
  PERFORM public.nepick_begin_write(p_user_id);

  DELETE FROM public.nepick_picks AS pick
  WHERE pick.board_id = p_board_id AND pick.user_id = p_user_id;

  RETURN FOUND;
END;
$$;

-- 일반 댓글
CREATE FUNCTION public.nepick_add_post(p_user_id uuid, p_board_store_id bigint, p_body text)
RETURNS bigint
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
  PERFORM public.nepick_begin_write(p_user_id);

  IF NOT EXISTS (
    SELECT 1 FROM public.nepick_visible_board_stores AS visible WHERE visible.id = p_board_store_id
  ) THEN
    RAISE EXCEPTION 'nepick_store_not_found';
  END IF;

  RETURN public.nepick_insert_post(p_user_id, p_board_store_id, p_body);
END;
$$;

-- 본인 글 삭제 (행은 남긴다). 추천 이유 글을 지워도 추천은 유지된다.
CREATE FUNCTION public.nepick_delete_post(p_user_id uuid, p_post_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
  PERFORM public.nepick_begin_write(p_user_id);

  UPDATE public.nepick_posts AS post
  SET deleted_at = now()
  WHERE post.id = p_post_id
    AND post.user_id = p_user_id
    AND post.deleted_at IS NULL;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'nepick_post_not_found';
  END IF;
END;
$$;

-- 추천(1) / 비추천(-1) / 취소(0). 같은 값을 다시 보내도 결과가 같다.
CREATE FUNCTION public.nepick_set_vote(p_user_id uuid, p_board_store_id bigint, p_value integer)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
  PERFORM public.nepick_begin_write(p_user_id);

  IF p_value IS NULL OR p_value NOT IN (1, 0, -1) THEN
    RAISE EXCEPTION 'nepick_invalid_vote';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.nepick_visible_board_stores AS visible WHERE visible.id = p_board_store_id
  ) THEN
    RAISE EXCEPTION 'nepick_store_not_found';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.nepick_picks AS pick
    WHERE pick.board_store_id = p_board_store_id AND pick.user_id = p_user_id
  ) THEN
    RAISE EXCEPTION 'nepick_vote_on_my_pick';
  END IF;

  IF p_value = 0 THEN
    DELETE FROM public.nepick_votes AS vote
    WHERE vote.board_store_id = p_board_store_id AND vote.user_id = p_user_id;
  ELSE
    INSERT INTO public.nepick_votes (board_store_id, user_id, value)
    VALUES (p_board_store_id, p_user_id, p_value)
    ON CONFLICT (board_store_id, user_id) DO UPDATE SET value = EXCLUDED.value;
  END IF;
END;
$$;

-- 신고: 가게나 글 중 하나. 같은 대상은 한 번, 24시간에 20건까지.
CREATE FUNCTION public.nepick_report(
  p_user_id uuid,
  p_board_store_id bigint,
  p_post_id bigint,
  p_reason text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_reason text := NULLIF(btrim(COALESCE(p_reason, ''), E' \t\r\n'), '');
BEGIN
  PERFORM public.nepick_begin_write(p_user_id);

  IF num_nonnulls(p_board_store_id, p_post_id) <> 1 THEN
    RAISE EXCEPTION 'nepick_invalid_report';
  END IF;

  IF char_length(v_reason) > 200 THEN
    RAISE EXCEPTION 'nepick_invalid_text';
  END IF;

  IF p_board_store_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.nepick_visible_board_stores AS visible WHERE visible.id = p_board_store_id
  ) THEN
    RAISE EXCEPTION 'nepick_store_not_found';
  END IF;

  IF p_post_id IS NOT NULL AND NOT EXISTS (
    SELECT 1
    FROM public.nepick_posts AS post
    JOIN public.nepick_visible_board_stores AS visible ON visible.id = post.board_store_id
    WHERE post.id = p_post_id AND NOT post.is_hidden AND post.deleted_at IS NULL
  ) THEN
    RAISE EXCEPTION 'nepick_post_not_found';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.nepick_reports AS report
    WHERE report.reporter_id = p_user_id
      AND (report.board_store_id = p_board_store_id OR report.post_id = p_post_id)
  ) THEN
    RAISE EXCEPTION 'nepick_already_reported';
  END IF;

  IF (
    SELECT COUNT(*) >= 20
    FROM public.nepick_reports AS report
    WHERE report.reporter_id = p_user_id AND report.created_at > now() - interval '24 hours'
  ) THEN
    RAISE EXCEPTION 'nepick_rate_limited';
  END IF;

  INSERT INTO public.nepick_reports (reporter_id, board_store_id, post_id, reason)
  VALUES (p_user_id, p_board_store_id, p_post_id, v_reason);
END;
$$;

-- 음식 제안: 24시간에 5건까지
CREATE FUNCTION public.nepick_suggest_food(p_user_id uuid, p_food_name text, p_reason text DEFAULT NULL)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_food_name text := btrim(COALESCE(p_food_name, ''), E' \t\r\n');
  v_reason text := NULLIF(btrim(COALESCE(p_reason, ''), E' \t\r\n'), '');
BEGIN
  PERFORM public.nepick_begin_write(p_user_id);

  IF char_length(v_food_name) NOT BETWEEN 1 AND 20 OR char_length(v_reason) > 200 THEN
    RAISE EXCEPTION 'nepick_invalid_text';
  END IF;

  IF (
    SELECT COUNT(*) >= 5
    FROM public.nepick_suggestions AS suggestion
    WHERE suggestion.user_id = p_user_id AND suggestion.created_at > now() - interval '24 hours'
  ) THEN
    RAISE EXCEPTION 'nepick_rate_limited';
  END IF;

  INSERT INTO public.nepick_suggestions (user_id, food_name, reason)
  VALUES (p_user_id, v_food_name, v_reason);
END;
$$;

