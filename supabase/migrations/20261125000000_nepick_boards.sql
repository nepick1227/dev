-- ============================================================
-- 네 픽 탭: 음식별 최고의 맛집 게시판 (이슈 #51, PR 1)
--
-- 접근 원칙
-- - 브라우저(anon, authenticated)는 아래 테이블·뷰·함수를 직접 읽거나 쓸 수 없다.
-- - app/api 서버 라우트가 로그인 사용자를 확인한 뒤 service_role로 함수를 호출한다.
--   금칙어 검사와 요청 제한을 건너뛰고 DB에 바로 쓰는 길을 막고,
--   profiles에서는 닉네임만 꺼내 내려 주기 위해서다.
-- - 함수는 모두 SECURITY INVOKER다. service_role만 실행할 수 있으므로
--   p_user_id / p_viewer_id에는 반드시 서버가 auth.getUser()로 확인한 id만 넘긴다.
-- - Supabase는 새 테이블·함수 권한을 anon, authenticated에게 기본으로 주므로
--   PUBLIC뿐 아니라 두 role에서도 직접 회수한다.
-- ============================================================

-- ------------------------------------------------------------
-- 1. 테이블
-- ------------------------------------------------------------

-- 게시판: 음식 하나. 운영자가 Supabase에서 추가한다.
CREATE TABLE public.nepick_boards (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug        text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND char_length(slug) <= 40),
  food_name   text NOT NULL UNIQUE CHECK (food_name = btrim(food_name) AND char_length(food_name) BETWEEN 1 AND 20),
  sort_order  integer NOT NULL DEFAULT 0,
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);

COMMENT ON COLUMN public.nepick_boards.slug IS '주소에 쓰는 이름. 영문 소문자, 숫자, 하이픈 (예: cheonggukjang)';
COMMENT ON COLUMN public.nepick_boards.is_active IS 'false면 화면에서 내려간다. 게시판은 지우지 말고 이 값을 끈다';

-- 게시판에 올라온 가게
CREATE TABLE public.nepick_board_stores (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  board_id    bigint NOT NULL REFERENCES public.nepick_boards(id) ON DELETE RESTRICT,
  store_id    bigint NOT NULL REFERENCES public.stores(id) ON DELETE RESTRICT,
  created_by  uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  is_hidden   boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (board_id, store_id),
  UNIQUE (id, board_id)
);

COMMENT ON COLUMN public.nepick_board_stores.is_hidden IS '운영자 숨김. true면 화면과 네픽지수에서 빠진다';

-- 글: 추천 이유와 일반 댓글. 한 단계만 있고 수정은 없다.
CREATE TABLE public.nepick_posts (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  board_store_id  bigint NOT NULL REFERENCES public.nepick_board_stores(id) ON DELETE RESTRICT,
  user_id         uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  body            text NOT NULL CHECK (char_length(btrim(body)) >= 1 AND char_length(body) <= 200),
  is_hidden       boolean NOT NULL DEFAULT false,
  deleted_at      timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id, board_store_id, user_id)
);

COMMENT ON COLUMN public.nepick_posts.is_hidden IS '운영자 숨김. 추천 이유 글을 숨기면 그 사람의 추천도 네픽지수에서 빠진다';
COMMENT ON COLUMN public.nepick_posts.deleted_at IS '본인이 삭제한 시각. 행은 남긴다';

CREATE INDEX idx_nepick_posts_board_store ON public.nepick_posts(board_store_id, created_at, id);
CREATE INDEX idx_nepick_posts_user_created ON public.nepick_posts(user_id, created_at DESC);

-- 추천(내 한 곳): 게시판마다 한 사람이 한 곳
CREATE TABLE public.nepick_picks (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  board_id        bigint NOT NULL,
  board_store_id  bigint NOT NULL,
  user_id         uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  reason_post_id  bigint NOT NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (board_id, user_id),
  -- 다른 게시판의 가게를 가리킬 수 없다
  FOREIGN KEY (board_store_id, board_id)
    REFERENCES public.nepick_board_stores(id, board_id) ON DELETE RESTRICT,
  -- 추천 이유는 같은 가게에 본인이 쓴 글이어야 한다
  FOREIGN KEY (reason_post_id, board_store_id, user_id)
    REFERENCES public.nepick_posts(id, board_store_id, user_id) ON DELETE CASCADE
);

CREATE INDEX idx_nepick_picks_board_store ON public.nepick_picks(board_store_id);
CREATE INDEX idx_nepick_picks_user ON public.nepick_picks(user_id);

-- 추천/비추천 버튼
CREATE TABLE public.nepick_votes (
  board_store_id  bigint NOT NULL REFERENCES public.nepick_board_stores(id) ON DELETE RESTRICT,
  user_id         uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  value           smallint NOT NULL CHECK (value IN (1, -1)),
  created_at      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (board_store_id, user_id)
);

CREATE INDEX idx_nepick_votes_user ON public.nepick_votes(user_id);

-- 신고: 가게 또는 글 중 하나
CREATE TABLE public.nepick_reports (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id     uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  board_store_id  bigint REFERENCES public.nepick_board_stores(id) ON DELETE RESTRICT,
  post_id         bigint REFERENCES public.nepick_posts(id) ON DELETE CASCADE,
  reason          text CHECK (char_length(reason) <= 200),
  created_at      timestamptz NOT NULL DEFAULT now(),
  CHECK (num_nonnulls(board_store_id, post_id) = 1),
  UNIQUE (reporter_id, board_store_id),
  UNIQUE (reporter_id, post_id)
);

CREATE INDEX idx_nepick_reports_board_store ON public.nepick_reports(board_store_id);
CREATE INDEX idx_nepick_reports_post ON public.nepick_reports(post_id);

-- 음식 제안: 운영자만 본다
CREATE TABLE public.nepick_suggestions (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  food_name   text NOT NULL CHECK (char_length(btrim(food_name)) >= 1 AND char_length(food_name) <= 20),
  reason      text CHECK (char_length(reason) <= 200),
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_nepick_suggestions_user_created ON public.nepick_suggestions(user_id, created_at DESC);

-- ------------------------------------------------------------
-- 2. RLS: 브라우저 접근을 모두 거절한다 (service_role은 RLS를 건너뛴다)
-- ------------------------------------------------------------
DO $$
DECLARE
  v_table text;
BEGIN
  FOREACH v_table IN ARRAY ARRAY[
    'nepick_boards',
    'nepick_board_stores',
    'nepick_posts',
    'nepick_picks',
    'nepick_votes',
    'nepick_reports',
    'nepick_suggestions'
  ]
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', v_table);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR ALL TO anon, authenticated USING (false) WITH CHECK (false)',
      v_table || '_no_client_access', v_table
    );
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated', v_table);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.%I TO service_role', v_table);
  END LOOP;
END;
$$;

-- ------------------------------------------------------------
-- 3. 집계 기준 뷰
-- ------------------------------------------------------------

-- 네픽지수와 딱지에 세는 추천. 숨긴 가게, 숨긴 추천 이유, 탈퇴한 사람의 추천은 뺀다.
CREATE VIEW public.nepick_active_picks
WITH (security_invoker = true)
AS
SELECT pick.board_id, pick.board_store_id, pick.user_id
FROM public.nepick_picks AS pick
JOIN public.profiles AS profile
  ON profile.id = pick.user_id AND profile.deleted_at IS NULL
JOIN public.nepick_board_stores AS board_store
  ON board_store.id = pick.board_store_id AND NOT board_store.is_hidden
JOIN public.nepick_posts AS reason_post
  ON reason_post.id = pick.reason_post_id AND NOT reason_post.is_hidden;

-- 화면에 보이는 가게와 집계. 지수가 0이고 보이는 글도 없으면 나오지 않는다.
-- 비추천 수는 정렬에만 쓰도록 vote_score(추천 - 비추천)로만 내보낸다.
CREATE VIEW public.nepick_visible_board_stores
WITH (security_invoker = true)
AS
SELECT
  board_store.id,
  board_store.board_id,
  board_store.store_id,
  board_store.created_at,
  picks.nepick_index,
  votes.up_count,
  votes.vote_score,
  posts.post_count
FROM public.nepick_board_stores AS board_store
JOIN public.nepick_boards AS board
  ON board.id = board_store.board_id AND board.is_active
CROSS JOIN LATERAL (
  SELECT COUNT(*)::integer AS nepick_index
  FROM public.nepick_active_picks AS pick
  WHERE pick.board_store_id = board_store.id
) AS picks
CROSS JOIN LATERAL (
  SELECT
    (COUNT(*) FILTER (WHERE vote.value = 1))::integer AS up_count,
    COALESCE(SUM(vote.value), 0)::integer AS vote_score
  FROM public.nepick_votes AS vote
  JOIN public.profiles AS profile
    ON profile.id = vote.user_id AND profile.deleted_at IS NULL
  WHERE vote.board_store_id = board_store.id
) AS votes
CROSS JOIN LATERAL (
  SELECT COUNT(*)::integer AS post_count
  FROM public.nepick_posts AS post
  WHERE post.board_store_id = board_store.id
    AND NOT post.is_hidden
    AND post.deleted_at IS NULL
) AS posts
WHERE NOT board_store.is_hidden
  AND (picks.nepick_index > 0 OR posts.post_count > 0);

REVOKE ALL ON public.nepick_active_picks FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.nepick_visible_board_stores FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.nepick_active_picks TO service_role;
GRANT SELECT ON public.nepick_visible_board_stores TO service_role;

